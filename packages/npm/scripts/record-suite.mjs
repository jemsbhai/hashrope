import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const label=process.argv[2];
if(!/^node\d+$/.test(label??'')) throw new Error('Usage: node scripts/record-suite.mjs node20|node24');
const sources=Object.fromEntries(['src','test'].flatMap(dir=>readdirSync(new URL(`../${dir}/`,import.meta.url)).filter(f=>dir==='src'?f.endsWith('.ts'):f.endsWith('.test.mjs')).map(f=>[`${dir}/${f}`,createHash('sha256').update(readFileSync(new URL(`../${dir}/${f}`,import.meta.url))).digest('hex')])));
const build=spawnSync(process.execPath,['scripts/build.mjs'],{cwd:root,encoding:'utf8'});
if(build.status!==0) throw new Error(build.stdout+build.stderr);
const files=readdirSync(new URL('../test/',import.meta.url)).filter(f=>f.endsWith('.test.mjs')).sort().map(f=>`test/${f}`);
const result=spawnSync(process.execPath,['--test','--test-reporter=tap',...files],{cwd:root,encoding:'utf8',maxBuffer:64*1024*1024,timeout:300000});
const output=(result.stdout??'')+(result.stderr??'');
writeFileSync(new URL(`../evidence/suite-${label}.tap`,import.meta.url),output);
const counts=Object.fromEntries([...output.matchAll(/^# (tests|suites|pass|fail|cancelled|skipped|todo) (\d+)$/gm)].map(m=>[m[1],Number(m[2])]));
const report={node:process.version,exitCode:result.status,counts,sourceSha256:sources,outputSha256:createHash('sha256').update(output).digest('hex')};
writeFileSync(new URL(`../evidence/suite-${label}.json`,import.meta.url),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));
if(result.error)throw result.error;
if(result.status!==0||counts.tests!==27636||counts.pass!==27636||counts.fail!==0||counts.skipped!==0)process.exit(1);
