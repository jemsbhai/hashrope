import test from 'node:test';
import assert from 'node:assert/strict';
import * as N from '../dist/esm/nodes.js';
import { PolynomialHash, MERSENNE_61, MERSENNE_127 } from '../dist/esm/polynomial.js';

const h = new PolynomialHash();
const bytes = (...values) => Uint8Array.of(...values);

test('leaf: owns Uint8Array bytes and read-only bigint metadata', () => {
  const input = bytes(0, 127, 255);
  const leaf = new N.Leaf(input, h);
  assert.deepEqual(leaf.data, input);
  assert.equal(leaf.len, 3n);
  assert.equal(leaf.weight, 1n);
  assert.equal(leaf.hashVal, h.hash(input));
  input[0] = 90;
  const copy = leaf.data;
  copy[1] = 90;
  assert.deepEqual(leaf.data, bytes(0, 127, 255));
  assert.notEqual(leaf.data, leaf.data);
  assert.equal(Object.isFrozen(leaf), true);
  assert.throws(() => { leaf.len = 99n; }, TypeError);
  assert.throws(() => { leaf.hashVal = 0n; }, TypeError);
});

test('leaf: Buffer inputs and hostile callbacks cannot mutate retained bytes', () => {
  const input = Buffer.from([7, 8, 9]);
  class MutatingHash extends PolynomialHash {
    hash(data) { data.fill(42); return 123n; }
  }
  const leaf = new N.Leaf(input, new MutatingHash());
  input.fill(1);
  const output = leaf.data;
  output.fill(2);
  assert.deepEqual(leaf.data, bytes(7, 8, 9));
  assert.equal(leaf.hashVal, 123n);
});

test('leaf: explicit bytes only, nonempty, and empty-rope accessors', () => {
  assert.throws(() => new N.Leaf(new Uint8Array(), h), /Leaf cannot be empty/);
  for (const bad of [null, undefined, '', [], [1], new Int8Array([1])]) {
    assert.throws(() => new N.Leaf(bad, h), TypeError);
    assert.throws(() => N.ropeFromBytes(bad, h), TypeError);
  }
  assert.equal(N.ropeFromBytes(new Uint8Array(), h), null);
  const leaf = N.ropeFromBytes(bytes(4, 5), h);
  assert.ok(leaf instanceof N.Leaf);
  assert.equal(N.ropeLen(null), 0n);
  assert.equal(N.ropeHash(null), 0n);
  assert.equal(N.ropeHeight(null), 0);
  assert.equal(N.ropeLen(leaf), 2n);
  assert.equal(N.ropeHash(leaf), h.hash(bytes(4, 5)));
  assert.equal(N.ropeHeight(leaf), 0);
});

test('nodes: internal and nested repetition preserve references and exact metadata', () => {
  const left = new N.Leaf(bytes(97, 98), h);
  const right = new N.Leaf(bytes(255), h);
  const joined = new N.Internal(left, right, h);
  assert.equal(joined.left, left);
  assert.equal(joined.right, right);
  assert.equal(joined.len, 3n);
  assert.equal(joined.weight, 2n);
  assert.equal(joined.hashVal, h.hash(bytes(97, 98, 255)));
  assert.equal(N.ropeHeight(joined), 1);
  const repeat = new N.RepeatNode(joined, 3, h);
  assert.equal(repeat.child, joined);
  assert.equal(repeat.reps, 3n);
  assert.equal(repeat.len, 9n);
  assert.equal(repeat.weight, 6n);
  assert.equal(repeat.hashVal, h.hash(bytes(97, 98, 255, 97, 98, 255, 97, 98, 255)));
  const nested = new N.RepeatNode(repeat, 2n, h);
  assert.equal(nested.child, repeat);
  assert.equal(nested.reps, 2n);
  assert.equal(N.ropeHeight(nested), 3);
  assert.equal(Object.isFrozen(joined), true);
  assert.equal(Object.isFrozen(repeat), true);
  assert.throws(() => { joined.left = right; }, TypeError);
  assert.throws(() => { repeat.reps = 5n; }, TypeError);
});

test('repeat: huge counts stay exact without expansion, with published-wheel oracle', () => {
  const q = (1n << 100n) + 3n;
  const leaf = new N.Leaf(bytes(97, 98), h);
  const node = new N.RepeatNode(leaf, q, h);
  // Generated by direct import of the SHA256-pinned published 0.2.2 wheel.
  assert.equal(node.len, 2535301200456458802993406410758n);
  assert.equal(node.weight, 1267650600228229401496703205379n);
  assert.equal(node.hashVal, 646049433255619606n);
  assert.equal(node.child, leaf);
  assert.equal(N.ropeHeight(node), 1);
});

test('constructors: invalid repetitions and child kinds are rejected', () => {
  const leaf = new N.Leaf(bytes(1), h);
  for (const q of [-2n, 0n, 1n]) assert.throws(() => new N.RepeatNode(leaf, q, h), /RepeatNode reps must be >= 2/);
  for (const q of [1.5, Number.MAX_SAFE_INTEGER + 1]) assert.throws(() => new N.RepeatNode(leaf, q, h), RangeError);
  for (const q of ['2', true, null]) assert.throws(() => new N.RepeatNode(leaf, q, h), TypeError);
  for (const bad of [null, undefined, {}, { len: 1n, weight: 1n, hashVal: 1n }]) {
    assert.throws(() => new N.Internal(bad, leaf, h), TypeError);
    assert.throws(() => new N.Internal(leaf, bad, h), TypeError);
    assert.throws(() => new N.RepeatNode(bad, 2n, h), TypeError);
  }
});

test('node callbacks: internal uses hashConcat; repeat uses power without hashRepeat', () => {
  const calls = [];
  class TracingHash extends PolynomialHash {
    hashConcat(a, length, b) { calls.push(['concat', a, length, b]); return super.hashConcat(a, length, b); }
    power(n) { calls.push(['power', n]); return super.power(n); }
    hashRepeat() { throw new Error('RepeatNode must use the reference primitive sequence'); }
  }
  const local = new TracingHash();
  const a = new N.Leaf(bytes(1, 2), local);
  const b = new N.Leaf(bytes(3), local);
  new N.Internal(a, b, local);
  assert.deepEqual(calls, [['concat', a.hashVal, b.len, b.hashVal], ['power', b.len]]);
  calls.length = 0;
  new N.RepeatNode(a, 3n, local);
  assert.deepEqual(calls, [['power', a.len]]);
});

test('materialization: exact fresh bytes for empty, leaves, internal and nested repeats', () => {
  assert.deepEqual(N.ropeToBytes(null), new Uint8Array());
  assert.notEqual(N.ropeToBytes(null), N.ropeToBytes(null));
  const leaf = new N.Leaf(bytes(1, 2, 255), h);
  const repeated = new N.RepeatNode(new N.RepeatNode(leaf, 3n, h), 2n, h);
  const root = new N.Internal(new N.Leaf(bytes(8), h), repeated, h);
  const expected = bytes(8, ...Array.from({ length: 6 }, () => [1, 2, 255]).flat());
  assert.deepEqual(N.ropeToBytes(root), expected);
  const first = N.ropeToBytes(root);
  first.fill(0);
  assert.deepEqual(N.ropeToBytes(root), expected);
  assert.deepEqual(N.ropeToBytes(leaf, 3), bytes(1, 2, 255));
  assert.throws(() => N.ropeToBytes(leaf, 2n), RangeError);
});

test('materialization: bounded allocation and explicit safe integer limits', () => {
  const leaf = new N.Leaf(bytes(2), h);
  const aboveDefault = new N.RepeatNode(leaf, 67_108_865n, h);
  const huge = new N.RepeatNode(leaf, (1n << 100n), h);
  assert.throws(() => N.ropeToBytes(aboveDefault), /materialization limit/);
  assert.throws(() => N.ropeToBytes(huge), /materialization limit/);
  for (const limit of [-1, 1.5, Number.MAX_SAFE_INTEGER + 1, -1n, 1n << 100n]) {
    assert.throws(() => N.ropeToBytes(null, limit), RangeError);
  }
  for (const limit of ['3', null, true]) assert.throws(() => N.ropeToBytes(leaf, limit), TypeError);
  assert.deepEqual(N.ropeToBytes(null, 0n), new Uint8Array());
  assert.throws(() => N.ropeToBytes({ len: 0n }), TypeError);
});

test('validation: accepts valid nodes and exact BB[2/7] boundary weights', () => {
  const leaf = new N.Leaf(bytes(1), h);
  assert.equal(N.validateRope(null), undefined);
  assert.equal(N.validateRope(leaf), undefined);
  const two = new N.RepeatNode(leaf, 2n, h);
  const five = new N.RepeatNode(leaf, 5n, h);
  assert.equal(N.validateRope(new N.Internal(two, five, h)), undefined);
  assert.equal(N.validateRope(new N.Internal(five, two, h)), undefined);
  assert.equal(N.validateRope(new N.RepeatNode(leaf, 1n << 100n, h)), undefined);
});

test('validation: reports unbalanced direct joins recursively with Python messages', () => {
  const leaf = new N.Leaf(bytes(1), h);
  const six = new N.RepeatNode(leaf, 6n, h);
  const heavy = new N.Internal(six, leaf, h);
  const light = new N.Internal(leaf, six, h);
  assert.throws(() => N.validateRope(heavy), { name: 'AssertionError', message: 'Left child too heavy: 6/7' });
  assert.throws(() => N.validateRope(light), { name: 'AssertionError', message: 'Left child too light: 1/7' });
  assert.throws(() => N.validateRope(new N.Internal(heavy, heavy, h)), N.RopeValidationError);
  assert.throws(() => N.validateRope(new N.RepeatNode(light, 2n, h)), N.RopeValidationError);
  for (const bad of [undefined, {}, new Uint8Array(), 0n]) assert.throws(() => N.validateRope(bad), TypeError);
});

test('validation: does not recompute hashes but enforces profile consistency', () => {
  class ZeroHash extends PolynomialHash { hash() { return 0n; } }
  const forgedHash = new N.Leaf(bytes(1, 2), new ZeroHash());
  const differentProfile = new N.Leaf(bytes(3), new PolynomialHash(MERSENNE_127, 257n));
  assert.throws(() => new N.Internal(forgedHash, differentProfile, h), /Incompatible hash profile/);
  assert.equal(N.validateRope(forgedHash, h), undefined);
  assert.notEqual(forgedHash.hashVal, h.hash(forgedHash.data));
});

test('structural equality: type, bytes, stored metadata and child shape all matter', () => {
  const a = new N.Leaf(bytes(1, 2), h);
  const b = new N.Leaf(bytes(1, 2), h);
  const c = new N.Leaf(bytes(1, 3), h);
  assert.equal(N.structuralEquals(null, null), true);
  assert.equal(N.structuralEquals(a, null), false);
  assert.equal(N.structuralEquals(null, a), false);
  assert.equal(N.structuralEquals(a, a), true);
  assert.equal(N.structuralEquals(a, b), true);
  assert.equal(N.structuralEquals(a, c), false);
  const splitShape = new N.Internal(new N.Leaf(bytes(1), h), new N.Leaf(bytes(2), h), h);
  assert.equal(splitShape.hashVal, a.hashVal);
  assert.equal(N.structuralEquals(a, splitShape), false);
  assert.equal(N.structuralEquals(new N.Internal(a, c, h), new N.Internal(b, c, h)), true);
  assert.equal(N.structuralEquals(new N.Internal(a, c, h), new N.Internal(c, b, h)), false);
  const huge = 1n << 100n;
  assert.equal(N.structuralEquals(new N.RepeatNode(a, huge, h), new N.RepeatNode(b, huge, h)), true);
  assert.equal(N.structuralEquals(new N.RepeatNode(a, huge, h), new N.RepeatNode(b, huge + 1n, h)), false);
  class ZeroHash extends PolynomialHash { hash() { return 0n; } }
  assert.equal(N.structuralEquals(a, new N.Leaf(a.data, new ZeroHash())), false);
  assert.throws(() => N.structuralEquals({}, {}), TypeError);
});

test('structural equality: documented base-131 collisions do not establish byte equality', () => {
  for (const prime of [MERSENNE_61, MERSENNE_127]) {
    const profile = new PolynomialHash(prime, 131n);
    const a = new N.Leaf(bytes(0, 131), profile);
    const b = new N.Leaf(bytes(1, 0), profile);
    assert.equal(a.hashVal, 263n);
    assert.equal(a.hashVal, b.hashVal);
    assert.equal(a.len, b.len);
    assert.equal(a.weight, b.weight);
    assert.equal(N.structuralEquals(a, b), false);
    assert.equal(N.structuralEquals(new N.RepeatNode(a, 3n, profile), new N.RepeatNode(b, 3n, profile)), false);
    assert.equal(N.structuralEquals(new N.Internal(a, a, profile), new N.Internal(a, b, profile)), false);
  }
});
